"""Pydantic schemas for Multi-Factor Physical Presence Attendance Verification."""

from datetime import datetime
from typing import List, Optional
import uuid
from pydantic import BaseModel, Field
from app.schemas.kiosk import DynamicQRPayload


class NetworkAudit(BaseModel):
    """Network presence audit parameters."""
    wifi_bssid: str = Field(..., description="BSSID (MAC address) of the connected office router")
    wifi_ssid: Optional[str] = Field(None, description="SSID name of the Wi-Fi network")


class LocationAudit(BaseModel):
    """GPS presence and mock detection."""
    latitude: float = Field(..., ge=-90.0, le=90.0)
    longitude: float = Field(..., ge=-180.0, le=180.0)
    accuracy_meters: Optional[float] = Field(None)
    is_mock: bool = Field(default=False, description="OS flag detecting mock/fake location provider")


class FaceVerificationAudit(BaseModel):
    """On-device AI facial liveness and embedding match."""
    liveness_passed: bool = Field(..., description="Flag verifying pupil/blink/depth 3D check passed on device")
    captured_embedding: List[float] = Field(..., description="Facial vector embedding generated by ML Kit/FaceNet")


class ClockInRequest(BaseModel):
    """Complete zero-trust physical attendance check-in verification request."""
    qr_payload: DynamicQRPayload
    network_audit: NetworkAudit
    location: LocationAudit
    face_verification: FaceVerificationAudit
    device_id: str = Field(..., description="Hardware device UUID matching registered device")


class ClockInResponse(BaseModel):
    """Successful clock-in response."""
    attendance_id: str
    status: str
    clock_in_time: str
    office_name: str
    similarity_score: float
    message: str


class ClockOutRequest(BaseModel):
    """Clock out submission."""
    attendance_id: str
    location: LocationAudit


class ClockOutResponse(BaseModel):
    """Clock out confirmation."""
    attendance_id: str
    clock_out_time: str
    total_shift_hours: float
    active_tasks_stopped: int
    message: str
